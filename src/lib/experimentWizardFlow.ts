import i18n from "i18next";

export const NEW_EXPERIMENT_PIPELINES_STEP = 1;
export const NEW_EXPERIMENT_DATASETS_STEP = 2;
export const NEW_EXPERIMENT_RUNTIME_GROUPING_STEP = 3;
export const NEW_EXPERIMENT_REVIEW_STEP = 4;
export const NEW_EXPERIMENT_LAUNCH_STEP = 5;

export const NEW_EXPERIMENT_FIRST_STEP = NEW_EXPERIMENT_PIPELINES_STEP;
export const NEW_EXPERIMENT_MAX_STEP = NEW_EXPERIMENT_LAUNCH_STEP;

export type NewExperimentWizardStep =
  | typeof NEW_EXPERIMENT_PIPELINES_STEP
  | typeof NEW_EXPERIMENT_DATASETS_STEP
  | typeof NEW_EXPERIMENT_RUNTIME_GROUPING_STEP
  | typeof NEW_EXPERIMENT_REVIEW_STEP
  | typeof NEW_EXPERIMENT_LAUNCH_STEP;

export interface NewExperimentStepProgressItem {
  id: NewExperimentWizardStep;
  label: string;
}

export interface NewExperimentStepProgressViewItem extends NewExperimentStepProgressItem {
  isActive: boolean;
  isCompleted: boolean;
  isLast: boolean;
}

export const NEW_EXPERIMENT_STEP_PROGRESS_ITEMS: ReadonlyArray<{ id: NewExperimentWizardStep; labelKey: string }> = [
  { id: NEW_EXPERIMENT_PIPELINES_STEP, labelKey: "newExperiment.steps.selectPipelines" },
  { id: NEW_EXPERIMENT_DATASETS_STEP, labelKey: "newExperiment.steps.selectDatasets" },
  { id: NEW_EXPERIMENT_RUNTIME_GROUPING_STEP, labelKey: "newExperiment.steps.sampleGrouping" },
  { id: NEW_EXPERIMENT_REVIEW_STEP, labelKey: "newExperiment.steps.review" },
  { id: NEW_EXPERIMENT_LAUNCH_STEP, labelKey: "newExperiment.steps.launch" },
];

export interface NewExperimentStepReadinessInput {
  currentStep: number;
  selectedPipelineCount: number;
  selectedDatasetCount: number;
  hasGroupingBlockingError: boolean;
}

export function buildNewExperimentStepProgress(
  currentStep: NewExperimentWizardStep,
): NewExperimentStepProgressViewItem[] {
  return NEW_EXPERIMENT_STEP_PROGRESS_ITEMS.map((step, index) => ({
    id: step.id,
    label: i18n.t(step.labelKey),
    isActive: step.id === currentStep,
    isCompleted: step.id < currentStep,
    isLast: index === NEW_EXPERIMENT_STEP_PROGRESS_ITEMS.length - 1,
  }));
}

export function canProceedNewExperimentStep({
  currentStep,
  selectedPipelineCount,
  selectedDatasetCount,
  hasGroupingBlockingError,
}: NewExperimentStepReadinessInput): boolean {
  if (currentStep === NEW_EXPERIMENT_PIPELINES_STEP) return selectedPipelineCount > 0;
  if (currentStep === NEW_EXPERIMENT_DATASETS_STEP) return selectedDatasetCount > 0;
  if (currentStep === NEW_EXPERIMENT_RUNTIME_GROUPING_STEP) return !hasGroupingBlockingError;
  return true;
}

export function getPreviousNewExperimentStep(step: NewExperimentWizardStep): NewExperimentWizardStep {
  return clampNewExperimentStep(step - 1);
}

export function getNextNewExperimentStep(step: NewExperimentWizardStep): NewExperimentWizardStep {
  return clampNewExperimentStep(step + 1);
}

export function shouldShowNewExperimentWizardActions(step: NewExperimentWizardStep): boolean {
  return step < NEW_EXPERIMENT_LAUNCH_STEP;
}

export function shouldApplyAutoGeneratedExperimentName({
  currentStep,
  currentName,
  autoGeneratedName,
}: {
  currentStep: NewExperimentWizardStep;
  currentName: string;
  autoGeneratedName: string;
}): boolean {
  return currentStep === NEW_EXPERIMENT_REVIEW_STEP && currentName === "" && autoGeneratedName !== "";
}

function clampNewExperimentStep(step: number): NewExperimentWizardStep {
  if (step <= NEW_EXPERIMENT_FIRST_STEP) return NEW_EXPERIMENT_FIRST_STEP;
  if (step >= NEW_EXPERIMENT_MAX_STEP) return NEW_EXPERIMENT_MAX_STEP;
  return step as NewExperimentWizardStep;
}
