export interface NewExperimentRuntimeGroupingStepPanelProps {
  planFlow: UseNewExperimentPlanFlowResult;
  selectionFlow: UseNewExperimentSelectionFlowResult;
}

export function NewExperimentRuntimeGroupingStepPanel({
  planFlow,
  selectionFlow,
}: NewExperimentRuntimeGroupingStepPanelProps) {
  return (
    <NewExperimentRuntimeGroupingStep
      datasetById={planFlow.datasetById}
      datasetGroupingStates={planFlow.datasetGroupingStates}
      groupingSelection={planFlow.groupingSelection}
      selectedDatasetIds={selectionFlow.selectedDatasetIds}
      splitGroupByByDataset={selectionFlow.splitGroupByByDataset}
      onDatasetGroupChange={(datasetId, groupBy) =>
        selectionFlow.setSplitGroupByByDataset((current) => ({ ...current, [datasetId]: groupBy }))
      }
    />
  );
}

