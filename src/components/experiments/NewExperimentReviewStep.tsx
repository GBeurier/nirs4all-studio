import type { CampaignPlanPreview } from "@/lib/campaignPlanPreviewTypes";
import type { ExperimentDatasetOption } from "@/lib/experimentDatasetOptions";
import type { NewExperimentExecutionEnvironmentDiagnostics } from "@/hooks/useNewExperimentExecutionEnvironment";
import {
  type DatasetRuntimeGroupingState,
  type SelectedPipelinesRuntimeGrouping,
} from "@/lib/runtimeSplitGrouping";
import { experimentReviewCopy } from "@/lib/experimentReviewPresentation";
import { RuntimeBackendSelector } from "@/components/runtime/RuntimeBackendSelector";

import { NewExperimentCampaignPlanPreview } from "./NewExperimentCampaignPlanPreview";
import { NewExperimentReviewDescriptionField } from "./NewExperimentReviewDescriptionField";
import { NewExperimentReviewExperimentCard } from "./NewExperimentReviewExperimentCard";
import { NewExperimentReviewRuntimeGroupingSummary } from "./NewExperimentReviewRuntimeGroupingSummary";

export interface NewExperimentReviewStepProps {
  autoGeneratedName: string;
  campaignPreview: CampaignPlanPreview;
  customExperimentName: string;
  datasetById: Map<string, ExperimentDatasetOption>;
  datasetGroupingStates: Record<string, DatasetRuntimeGroupingState>;
  executionEnvironmentDiagnostics: NewExperimentExecutionEnvironmentDiagnostics;
  experimentDescription: string;
  groupingSelection: SelectedPipelinesRuntimeGrouping;
  runtimeEngine?: string | null;
  selectedDatasetIds: string[];
  allowFallback?: boolean;
  onExperimentDescriptionChange: (value: string) => void;
  onExperimentNameChange: (value: string) => void;
  onRuntimeEngineChange?: (value: string | null) => void;
  onAllowFallbackChange?: (value: boolean) => void;
}

export function NewExperimentReviewStep({
  autoGeneratedName,
  campaignPreview,
  customExperimentName,
  datasetById,
  datasetGroupingStates,
  executionEnvironmentDiagnostics,
  experimentDescription,
  groupingSelection,
  runtimeEngine,
  selectedDatasetIds,
  allowFallback = false,
  onExperimentDescriptionChange,
  onExperimentNameChange,
  onRuntimeEngineChange,
  onAllowFallbackChange,
}: NewExperimentReviewStepProps) {
  return (
    <div className="space-y-6">
      <h2 className="text-lg font-semibold text-foreground">{experimentReviewCopy.title}</h2>
      <NewExperimentReviewExperimentCard
        autoGeneratedName={autoGeneratedName}
        campaignSummary={campaignPreview.summary}
        customExperimentName={customExperimentName}
        onExperimentNameChange={onExperimentNameChange}
      />
      <NewExperimentCampaignPlanPreview
        campaignPreview={campaignPreview}
        executionEnvironmentDiagnostics={executionEnvironmentDiagnostics}
      />
      {onRuntimeEngineChange && onAllowFallbackChange && (
        <RuntimeBackendSelector
          runtimeEngine={runtimeEngine ?? null}
          allowFallback={allowFallback}
          onRuntimeEngineChange={onRuntimeEngineChange}
          onAllowFallbackChange={onAllowFallbackChange}
        />
      )}
      <NewExperimentReviewDescriptionField
        experimentDescription={experimentDescription}
        onExperimentDescriptionChange={onExperimentDescriptionChange}
      />
      <NewExperimentReviewRuntimeGroupingSummary
        datasetById={datasetById}
        datasetGroupingStates={datasetGroupingStates}
        groupingSelection={groupingSelection}
        selectedDatasetIds={selectedDatasetIds}
      />
    </div>
  );
}
