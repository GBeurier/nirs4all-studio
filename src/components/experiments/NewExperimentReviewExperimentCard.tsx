import type { CampaignPlanSummary } from "@/lib/campaignSpecTypes";
import { buildExperimentReviewSummaryFields } from "@/lib/experimentReviewPresentation";

import { NewExperimentReviewNameField } from "./NewExperimentReviewNameField";
import { NewExperimentReviewSummaryFields } from "./NewExperimentReviewSummaryFields";

export interface NewExperimentReviewExperimentCardProps {
  autoGeneratedName: string;
  campaignSummary: CampaignPlanSummary;
  customExperimentName: string;
  onExperimentNameChange: (value: string) => void;
}

export function NewExperimentReviewExperimentCard({
  autoGeneratedName,
  campaignSummary,
  customExperimentName,
  onExperimentNameChange,
}: NewExperimentReviewExperimentCardProps) {
  const summaryFields = buildExperimentReviewSummaryFields(campaignSummary);

  return (
    <div className="space-y-4 rounded-lg border border-border/60 bg-muted/30 p-4">
      <NewExperimentReviewNameField
        autoGeneratedName={autoGeneratedName}
        customExperimentName={customExperimentName}
        onExperimentNameChange={onExperimentNameChange}
      />
      <NewExperimentReviewSummaryFields fields={summaryFields} />
    </div>
  );
}
