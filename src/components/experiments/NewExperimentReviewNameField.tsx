import { Input } from "@/components/ui/input";
import { experimentReviewCopy } from "@/lib/experimentReviewPresentation";

export interface NewExperimentReviewNameFieldProps {
  autoGeneratedName: string;
  customExperimentName: string;
  onExperimentNameChange: (value: string) => void;
}

export function NewExperimentReviewNameField({
  autoGeneratedName,
  customExperimentName,
  onExperimentNameChange,
}: NewExperimentReviewNameFieldProps) {
  return (
    <div>
      <label className="text-sm text-muted-foreground">{experimentReviewCopy.nameLabel}</label>
      <Input
        value={customExperimentName}
        onChange={(event) => onExperimentNameChange(event.target.value)}
        placeholder={autoGeneratedName}
        className="mt-1"
      />
    </div>
  );
}
